function shuffleArray(array) {
    const shuffled = [...array];
    for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    return shuffled;
}

function generateNames() {
    const modeButtons = document.querySelectorAll('.mode-btn');
    let currentMode = 'random';
    
    modeButtons.forEach(btn => {
        if (btn.classList.contains('active')) {
            currentMode = btn.dataset.mode;
        }
    });
    
    let names;
    
    if (currentMode === 'male') {
        names = shuffleArray(maleNames).slice(0, 16);
    } else if (currentMode === 'female') {
        names = shuffleArray(femaleNames).slice(0, 16);
    } else {
        const combined = [...maleNames, ...femaleNames];
        names = shuffleArray(combined).slice(0, 16);
    }
    
    const namesGrid = document.getElementById('namesGrid');
    namesGrid.innerHTML = '';
    
    names.forEach(nameObj => {
        const card = document.createElement('div');
        card.className = 'name-card';
        
        const nameText = document.createElement('div');
        nameText.className = 'name-text';
        nameText.textContent = nameObj.name;
        
        const genderBadge = document.createElement('div');
        genderBadge.className = 'name-gender';
        genderBadge.textContent = currentMode === 'random' ? 'Random' : (currentMode === 'male' ? 'Male' : 'Female');
        
        const meaningText = document.createElement('div');
        meaningText.className = 'name-meaning';
        meaningText.textContent = nameObj.meaning;
        
        card.appendChild(nameText);
        card.appendChild(genderBadge);
        card.appendChild(meaningText);
        
        namesGrid.appendChild(card);
    });
}

document.querySelectorAll('.mode-btn').forEach(btn => {
    btn.addEventListener('click', () => {
        document.querySelectorAll('.mode-btn').forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
    });
});

document.addEventListener('DOMContentLoaded', generateNames);