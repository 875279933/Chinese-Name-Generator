let currentMode = 'random';

function shuffleArray(array) {
    const shuffled = [...array];
    for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    return shuffled;
}

function generateNames() {
    const grid = document.getElementById('namesGrid');
    let pool;
    
    if (currentMode === 'random') {
        pool = shuffleArray([...maleNames, ...femaleNames]);
    } else if (currentMode === 'male') {
        pool = shuffleArray([...maleNames]);
    } else {
        pool = shuffleArray([...femaleNames]);
    }
    
    const selected = pool.slice(0, 16);
    
    grid.innerHTML = selected.map(item => `
        <div class="name-card">
            <div class="name-text">${item.name}</div>
            <div class="name-gender">${currentMode === 'female' ? 'Female' : currentMode === 'male' ? 'Male' : 'Mixed'}</div>
            <div class="name-meaning">${item.meaning}</div>
        </div>
    `).join('');
}

document.querySelectorAll('.mode-btn').forEach(btn => {
    btn.addEventListener('click', function() {
        document.querySelectorAll('.mode-btn').forEach(b => b.classList.remove('active'));
        this.classList.add('active');
        currentMode = this.dataset.mode;
        generateNames();
    });
});

