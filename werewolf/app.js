let currentMode = 'random';

function shuffleArray(array) {
    for (let i = array.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [array[i], array[j]] = [array[j], array[i]];
    }
    return array;
}

document.querySelectorAll('.mode-btn').forEach(btn => {
    btn.addEventListener('click', function() {
        document.querySelectorAll('.mode-btn').forEach(b => b.classList.remove('active'));
        this.classList.add('active');
        currentMode = this.dataset.mode;
    });
});

function generateNames() {
    const grid = document.getElementById('namesGrid');
    grid.innerHTML = '';
    
    let names = [];
    
    if (currentMode === 'male') {
        names = shuffleArray([...maleNames]).slice(0, 16).map(n => ({...n, gender: 'Male'}));
    } else if (currentMode === 'female') {
        names = shuffleArray([...femaleNames]).slice(0, 16).map(n => ({...n, gender: 'Female'}));
    } else {
        const allNames = [...maleNames.map(n => ({...n, gender: 'Male'})), ...femaleNames.map(n => ({...n, gender: 'Female'}))];
        names = shuffleArray(allNames).slice(0, 16);
    }
    
    names.forEach(nameData => {
        const card = document.createElement('div');
        card.className = 'name-card';
        card.innerHTML = `
            <div class="name-text">${nameData.name}</div>
            <div class="name-gender">${nameData.gender} Werewolf</div>
            <div class="name-meaning">${nameData.meaning}</div>
        `;
        grid.appendChild(card);
    });
}

generateNames();
